#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const OVERRIDES_ROOT = path.resolve('src/localization/overrides');
const REGISTRY_PATH = path.join(OVERRIDES_ROOT, 'registry.ts');

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) {
    return files;
  }

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'registry.ts') {
      continue;
    }
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, files);
    } else if (/\.(tsx?|jsx?)$/.test(entry.name)) {
      files.push(path.relative(OVERRIDES_ROOT, full));
    }
  }

  return files.sort();
}

const overrides = walk(OVERRIDES_ROOT);
const srcPaths = overrides.map((f) => `src/${f.replace(/\\/g, '/')}`);

const content = `// Auto-generated by scripts/generate-override-registry.mjs — do not edit manually.
export const CN_OVERRIDE_SOURCE_PATHS = ${JSON.stringify(srcPaths, null, 2)} as const;

export type CnOverrideSourcePath = (typeof CN_OVERRIDE_SOURCE_PATHS)[number];
`;

fs.mkdirSync(OVERRIDES_ROOT, { recursive: true });
fs.writeFileSync(REGISTRY_PATH, content);
console.log(`Wrote ${REGISTRY_PATH} (${srcPaths.length} overrides)`);
