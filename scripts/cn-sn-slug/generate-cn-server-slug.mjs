#!/usr/bin/env node
/**
 * 生成 src/common/CN_SERVER_SLUG.ts(CN 服务器 中文名→罗马化 slug 映射)。
 *
 * 数据源:wcl-mp-client `src/assets/datas/regions.ts`(与 CN armory 网关同源)。
 * 当 wcl-mp-client 的服务器表更新时,重新运行本脚本即可。
 *
 * 用法:
 *   node scripts/cn-sn-slug/generate-cn-server-slug.mjs \
 *     <path-to-regions.ts> [path-to-output]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const DEFAULT_SOURCE = process.env.WCL_MP_CLIENT_REGIONS;
const DEFAULT_OUTPUT = path.resolve(__dirname, '../../src/common/CN_SERVER_SLUG.ts');

function main() {
  const source = process.argv[2] || DEFAULT_SOURCE;
  const output = process.argv[3] || DEFAULT_OUTPUT;

  if (!source || !fs.existsSync(source)) {
    console.error(`源文件不存在: ${source || '(未指定)'}`);
    console.error(
      '用法: node scripts/cn-sn-slug/generate-cn-server-slug.mjs <path/to/regions.ts> [output]',
    );
    console.error('或设置 env WCL_MP_CLIENT_REGIONS=<path> 后直接运行。');
    process.exit(1);
  }

  const src = fs.readFileSync(source, 'utf8');
  // 定位 CN 服块:第一个 slug: 'CN' 之后最近的 servers: [...]
  const cnIdx = src.indexOf("slug: 'CN'");
  if (cnIdx === -1) {
    console.error('未找到 slug 为 CN 的区块,源文件格式可能变了。');
    process.exit(1);
  }
  const serversStart = src.indexOf('servers: [', cnIdx);
  if (serversStart === -1) {
    console.error('CN 区块内未找到 servers: [。源文件格式可能变了。');
    process.exit(1);
  }
  const blockStart = src.indexOf('[', serversStart);
  let depth = 0;
  let blockEnd = -1;
  for (let i = blockStart; i < src.length; i += 1) {
    if (src[i] === '[') depth += 1;
    else if (src[i] === ']') {
      depth -= 1;
      if (depth === 0) {
        blockEnd = i;
        break;
      }
    }
  }
  if (blockEnd === -1) {
    console.error('CN servers 块未闭合。');
    process.exit(1);
  }

  const block = src.slice(blockStart, blockEnd + 1);
  // 匹配 { id: N, name: 'x', slug: 'y' }
  const re = /\{\s*id:\s*\d+,\s*name:\s*'([^']+)',\s*slug:\s*'([^']+)'\s*\}/g;
  const rows = [];
  let m;
  while ((m = re.exec(block))) {
    rows.push({ name: m[1], slug: m[2] });
  }
  if (rows.length === 0) {
    console.error('CN servers 块内没解析到任何 {id,name,slug}。');
    process.exit(1);
  }

  const lines = rows
    .map((r) => `  '${r.name.replaceAll("'", "\\'")}': '${r.slug.replaceAll("'", "\\'")}',`)
    .join('\n');
  const out = `// @generated by scripts/cn-sn-slug/generate-cn-server-slug.mjs - DO NOT EDIT DIRECTLY.\n// 数据源:wcl-mp-client src/assets/datas/regions.ts (CN servers slug)。\nconst CN_SERVER_SLUG: Record<string, string> = {\n${lines}\n};\nexport default CN_SERVER_SLUG;\n`;

  fs.writeFileSync(output, out);
  console.log(`生成 ${rows.length} 个 CN 服务器映射 → ${output}`);
}

main();
