/**
 * 根据 spell ID 获取中文名
 * @param id - WCL spell/game ID
 * @returns 中文名，未匹配时返回 null
 */
export function getSpellCnName(id: number): string | null {
  return SPELL_CN_NAMES[id] ?? null;
}

/**
 * 根据英文技能名获取中文名（不区分大小写，不依赖 ID）
 * 用于 ID 不可用或名称映射的场景。
 *
 * 反向索引在首次调用时自动从 SPELL_CN_NAMES 构建，
 * 并由手动维护的英文→中文映射表补充。
 */
export function getSpellCnNameByEnglish(englishName: string): string | null {
  if (!englishName) return null;
  const index = buildEnCnIndex();
  return index.get(englishName.trim().toLowerCase()) ?? null;
}
